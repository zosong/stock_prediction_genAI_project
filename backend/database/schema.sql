CREATE TABLE company (
  company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name VARCHAR(255) NOT NULL,
  stock_ticker VARCHAR(10) NOT NULL UNIQUE,
  sector VARCHAR(100),
  industry VARCHAR(100)
);

CREATE TABLE article (
  article_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(500) NOT NULL,
  summary TEXT NOT NULL,
  publication_date TIMESTAMPTZ NOT NULL,
  url VARCHAR(1000) NOT NULL,
  source_location VARCHAR(2000)
);

CREATE TABLE article_company_link (
  link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id BIGINT NOT NULL REFERENCES article(article_id) ON DELETE CASCADE,
  company_id BIGINT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
  UNIQUE (article_id, company_id)
);

CREATE TABLE official_report (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
  title VARCHAR(500) NOT NULL,
  report_type VARCHAR(100) NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  publication_date TIMESTAMPTZ NOT NULL,
  summary TEXT,
  url VARCHAR(1000) NOT NULL,
  source_location VARCHAR(2000)
);

CREATE TABLE social_media (
  post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform VARCHAR(20) NOT NULL,
  user_id VARCHAR(100) NOT NULL,
  author_handle VARCHAR(100) NOT NULL,
  content TEXT NOT NULL,
  post_time TIMESTAMPTZ NOT NULL,
  url VARCHAR(1000) NOT NULL,
  like_count INT DEFAULT 0,
  repost_count INT DEFAULT 0
);

CREATE TABLE social_post_company_link (
  link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES social_media(post_id) ON DELETE CASCADE,
  company_id BIGINT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
  UNIQUE (post_id, company_id)
);

CREATE TABLE prediction_summary (
  prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trend VARCHAR(10) NOT NULL,
  confidence NUMERIC(5,2) NOT NULL,
  reason TEXT,
  prediction_time TIMESTAMPTZ NOT NULL,
  company_id BIGINT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
  model_version VARCHAR(50),
  CHECK (trend IN ('UP','DOWN','STABLE')),
  CHECK (confidence >= 0 AND confidence <= 100)
);

CREATE TABLE price_history (
  price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
  trade_date DATE NOT NULL,
  open_price NUMERIC(10,2),
  close_price NUMERIC(10,2),
  high_price NUMERIC(10,2),
  low_price NUMERIC(10,2),
  volume BIGINT,
  UNIQUE (company_id, trade_date)
);

CREATE TABLE article_sentiment (
  article_id BIGINT PRIMARY KEY
    REFERENCES article(article_id) ON DELETE CASCADE,
  sentiment_label VARCHAR(20) NOT NULL,
  sentiment_score NUMERIC(6,3) NOT NULL,  -- allow e.g. -1.000 to 1.000 or 0..1
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (sentiment_label IN ('bullish', 'bearish', 'neutral')),
  CHECK (sentiment_score >= -1 AND sentiment_score <= 1)
);

-- Helpful indexes
CREATE INDEX idx_price_history_company_date ON price_history(company_id, trade_date);
CREATE INDEX idx_article_pub_date ON article(publication_date);
CREATE INDEX idx_social_media_post_time ON social_media(post_time);
CREATE INDEX idx_prediction_company_time ON prediction_summary(company_id, prediction_time);
CREATE INDEX idx_article_pub_date ON article(publication_date DESC);
